#pragma once

#include <ratio>
#include <vector>
#include <stack>

using namespace std;

/*
739. 每日温度

给定一个整数数组 temperatures ，表示每天的温度，返回一个数组 answer ，其中 answer[i] 是指对于第 i 天，
下一个更高温度出现在几天后。如果气温在这之后都不会升高，请在该位置用 0 来代替。

示例 1：
    输入: temperatures = [73,74,75,71,69,72,76,73]
    输出: [1,1,4,2,1,1,0,0]
    解释:
        第 1 天的温度是 73 ，第 2 天的温度是 74 ，比 73 高，所以对于第 1 天，答案是 1。
        第 2 天的温度是 74 ，第 3 天的温度是 75 ，比 74 高，所以对于第 2 天，答案是 1。
        第 3 天的温度是 75 ，第 7 天的温度是 76 ，比 75 高，所以对于第 3 天，答案是 4。
        第 4 天的温度是 71 ，第 6 天的温度是 72 ，比 71 高，所以对于第 4 天，答案是 2。
        第 5 天的温度是 69 ，第 6 天的温度是 72 ，比 69 高，所以对于第 5 天，答案是 1。
        第 6 天的温度是 72 ，第 7 天的温度是 76 ，比 72 高，所以对于第 6 天，答案是 1。
        第 7 天的温度是 76 ，后面没有更高的温度，所以对于第 7 天，答案是 0。
        第 8 天的温度是 73 ，后面没有更高的温度，所以对于第 8 天，答案是 0。

示例 2：
    输入: temperatures = [30,40,50,60]
    输出: [1,1,1,0]

示例 3：
    输入: temperatures = [30,60,90]
    输出: [1,1,0]

提示：
    - 1 <= temperatures.length <= 10^5
    - 30 <= temperatures[i] <= 100

解题思路：
    1. 使用单调栈解决，栈中存储温度的下标
    2. 栈中的温度从底到顶递减（栈顶温度最低）
    3. 遍历温度数组：
       - 如果当前温度高于栈顶温度，则可以更新栈顶温度的等待天数
       - 如果当前温度不高于栈顶温度，则将当前温度入栈
    4. 最终栈中剩余的温度，其等待天数都为0（找不到更高温度）

时间复杂度：O(n)
    - 每个元素最多入栈和出栈一次

空间复杂度：O(n)
    - 栈的大小最大为温度数组的长度
*/

class Solution {
public:
    /**
     * @brief 计算每个温度需要等待的天数
     * @param temperatures 温度数组
     * @return 返回等待天数数组
     *
     * 使用单调栈解法：
     * 1. 栈中存储温度的下标，栈中温度从底到顶递减
     * 2. 遇到更高温度时，可以更新栈中所有较低温度的等待天数
     * 3. 最终栈中剩余的温度（找不到更高温度的）等待天数保持为0
     */
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        vector<int> result(n, 0);    // 初始化结果数组，默认等待天数为0
        stack<int> st;               // 单调栈，存储温度的下标

        for (int i = 0; i < n; ++i)  // 遍历每一天的温度
        {
            // 当栈不为空，且当前温度高于栈顶温度时
            // 说明找到了栈顶温度的下一个更高温度
            while (!st.empty() && temperatures[i] > temperatures[st.top()])
            {
                result[st.top()] = i - st.top();  // 计算等待天数：当前天数 - 栈顶温度的天数
                st.pop();                         // 栈顶温度已找到答案，出栈
            }
            st.push(i);  // 将当前温度的下标入栈
        }

        return result;  // 栈中剩余的温度都找不到更高温度，保持默认值0
    }
};
